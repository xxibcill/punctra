import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = path.join(repositoryRoot, "docs/api/browser-sdk.md");
const viewerManifest = JSON.parse(await readFile(
  path.join(repositoryRoot, "apps/browser-demo/web/package.json"),
  "utf8",
));
const declarationSections = [
  ["@punctra/viewer", "apps/browser-demo/web/sdk.d.ts"],
  ["Viewer model", "apps/browser-demo/web/viewer-api.d.ts"],
  ["Input normalizer", "apps/browser-demo/web/viewer-input.d.ts"],
  ["Immutable-LAS exact bridge", "apps/browser-demo/web/exact-query.d.ts"],
  ["@punctra/react", "packages/react/index.d.ts"],
];

const sections = await Promise.all(declarationSections.map(async ([title, relativePath]) => {
  const sourceDeclaration = await readFile(path.join(repositoryRoot, relativePath), "utf8");
  const declaration = publicDeclaration(relativePath, sourceDeclaration);
  return `## ${title}\n\nSource declaration: \`${relativePath}\`\n\n\`\`\`ts\n${declaration.trim()}\n\`\`\``;
}));

const generated = `# Browser SDK API Reference

Generated by \`scripts/generate-browser-sdk-reference.mjs\` from the declarations
packed in Punctra \`${viewerManifest.version}\`. Do not edit this file directly.

The supported package entries are \`@punctra/viewer\`, \`@punctra/viewer/input\`,
\`@punctra/viewer/exact-query\`, and \`@punctra/react\`. The Wasm bindings,
worker protocol, cache implementation, and renderer host remain private package
assets even when their files are visible in a packed artifact.

${sections.join("\n\n")}
`;

if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== generated) {
    throw new Error("docs/api/browser-sdk.md is stale; regenerate it before verification");
  }
} else {
  await writeFile(outputPath, generated);
}

function publicDeclaration(relativePath, declaration) {
  if (relativePath !== "apps/browser-demo/web/viewer-api.d.ts") return declaration;
  return declaration.replace(
    /export interface BrowserViewerOptions \{[\s\S]*?\n\}\n\nexport function createBrowserViewer\([\s\S]*?;\n\n/,
    "",
  );
}
