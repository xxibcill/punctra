import { spawnSync } from "node:child_process";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const artifactDirectory = path.join(repositoryRoot, "target/npm");
const outputPath = path.join(repositoryRoot, "docs/api/browser-sdk.md");

export async function generateBrowserSdkReference() {
  const [viewerArtifact, reactArtifact] = await Promise.all([
    onlyArtifact("punctra-viewer-"),
    onlyArtifact("punctra-react-"),
  ]);
  const viewerManifest = packedJson(viewerArtifact, "package/package.json");
  const reactManifest = packedJson(reactArtifact, "package/package.json");
  requirePackage(viewerManifest, "@punctra/viewer");
  requirePackage(reactManifest, "@punctra/react");
  if (reactManifest.version !== viewerManifest.version) {
    throw new Error("Packed viewer and React artifacts must have the same release version.");
  }

  const declarations = [
    ["@punctra/viewer", viewerArtifact, viewerManifest.name, "sdk.d.ts"],
    ["Viewer model", viewerArtifact, viewerManifest.name, "viewer-api.d.ts"],
    ["Input normalizer", viewerArtifact, viewerManifest.name, "viewer-input.d.ts"],
    ["Immutable-LAS exact bridge", viewerArtifact, viewerManifest.name, "exact-query.d.ts"],
    ["@punctra/react", reactArtifact, reactManifest.name, "index.d.ts"],
  ];
  const sections = declarations.map(([title, artifact, packageName, declarationPath]) => {
    const declaration = publicDeclaration(
      declarationPath,
      packedText(artifact, `package/${declarationPath}`),
    );
    return `## ${title}\n\nPacked declaration: \`${packageName}/${declarationPath}\`\n\n\`\`\`ts\n${declaration.trim()}\n\`\`\``;
  });

  return `# Browser SDK API Reference

Generated by \`scripts/generate-browser-sdk-reference.mjs\` from the declarations
packed in Punctra \`${viewerManifest.version}\`. Do not edit this file directly.

The supported package entries are \`@punctra/viewer\`, \`@punctra/viewer/input\`,
\`@punctra/viewer/exact-query\`, and \`@punctra/react\`. The Wasm bindings,
worker protocol, cache implementation, and renderer host remain private package
assets even when their files are visible in a packed artifact.

${sections.join("\n\n")}
`;
}

export function publicDeclaration(declarationPath, declaration) {
  if (declarationPath !== "viewer-api.d.ts") return declaration;
  return declaration.replace(
    /export interface BrowserViewerOptions \{[\s\S]*?\n\}\n\nexport function createBrowserViewer\([\s\S]*?;\n\n/,
    "",
  );
}

async function onlyArtifact(prefix) {
  const matches = (await readdir(artifactDirectory))
    .filter((name) => name.startsWith(prefix) && name.endsWith(".tgz"));
  if (matches.length !== 1) {
    throw new Error(`Expected one ${prefix} artifact, found ${matches.join(", ")}.`);
  }
  return path.join(artifactDirectory, matches[0]);
}

function packedJson(artifact, entry) {
  return JSON.parse(packedText(artifact, entry));
}

function packedText(artifact, entry) {
  const result = spawnSync("tar", ["-xOzf", artifact, entry], {
    cwd: repositoryRoot,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  });
  if (result.status !== 0) {
    throw new Error(`Could not read ${entry} from ${path.basename(artifact)}: ${result.stderr}`);
  }
  return result.stdout;
}

function requirePackage(manifest, expectedName) {
  if (manifest?.name !== expectedName || typeof manifest.version !== "string") {
    throw new Error(`Packed artifact does not contain the expected ${expectedName} manifest.`);
  }
}

async function main() {
  const generated = await generateBrowserSdkReference();
  if (process.argv.includes("--check")) {
    const current = await readFile(outputPath, "utf8").catch(() => "");
    if (current !== generated) {
      throw new Error("docs/api/browser-sdk.md is stale; regenerate it before verification");
    }
    return;
  }
  await writeFile(outputPath, generated);
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  await main();
}
