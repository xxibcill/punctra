    fn derive_condition_facts(
        sample: &[u8],
        origin: [f64; 3],
    ) -> Result<(Value, Vec<&'static str>), Box<dyn Error>> {
        let records = decode_visual_records(sample)?;
        let bounds = relative_bounds(&records);
        let summary = ConditionAccumulator::new(bounds).summarize(&records, origin)?;
        let derived_conditions = derived_condition_names(&summary);
        let facts = condition_facts_json(&summary, &derived_conditions);
        Ok((facts, derived_conditions))
    }

    struct ConditionSummary {
        relative_bounds: ([f64; 3], [f64; 3]),
        minimum_positive_axis_spacing: f64,
        occupied_cells: usize,
        empty_cells: usize,
        singleton_cells: usize,
        dense_cells: usize,
        maximum_points_per_cell: u64,
        layered_cells: usize,
        maximum_cell_z_span: f64,
        occupied_depth_bins: usize,
        intensity_minimum: u16,
        intensity_maximum: u16,
        rgb_minimum: u16,
        rgb_maximum: u16,
        classifications: Vec<Value>,
        maximum_absolute_world_origin: f64,
    }

    struct ConditionAccumulator {
        relative_bounds: ([f64; 3], [f64; 3]),
        xy_counts: Vec<u64>,
        xy_minimum_z: Vec<f64>,
        xy_maximum_z: Vec<f64>,
        depth_counts: Vec<u64>,
        intensity_minimum: u16,
        intensity_maximum: u16,
        rgb_minimum: u16,
        rgb_maximum: u16,
        classification_counts: [u64; 256],
    }

    impl ConditionAccumulator {
        fn new(relative_bounds: ([f64; 3], [f64; 3])) -> Self {
            let cell_count = CONDITION_GRID_BINS * CONDITION_GRID_BINS;
            Self {
                relative_bounds,
                xy_counts: vec![0; cell_count],
                xy_minimum_z: vec![f64::INFINITY; cell_count],
                xy_maximum_z: vec![f64::NEG_INFINITY; cell_count],
                depth_counts: vec![0; CONDITION_GRID_BINS],
                intensity_minimum: u16::MAX,
                intensity_maximum: u16::MIN,
                rgb_minimum: u16::MAX,
                rgb_maximum: u16::MIN,
                classification_counts: [0; 256],
            }
        }

        fn summarize(
            mut self,
            records: &[VisualRecord],
            origin: [f64; 3],
        ) -> Result<ConditionSummary, Box<dyn Error>> {
            for record in records {
                self.observe(record);
            }
            let occupied_cells = self.xy_counts.iter().filter(|&&count| count > 0).count();
            let singleton_cells = self.xy_counts.iter().filter(|&&count| count == 1).count();
            let dense_cells = self
                .xy_counts
                .iter()
                .filter(|&&count| count >= DENSE_CELL_MINIMUM_POINTS)
                .count();
            let spans = self.layered_spans();
            let minimum_positive_axis_spacing = minimum_positive_axis_spacing(records)
                .ok_or("the Autzen visual sample has no positive axis spacing")?;
            Ok(ConditionSummary {
                relative_bounds: self.relative_bounds,
                minimum_positive_axis_spacing,
                occupied_cells,
                empty_cells: self.xy_counts.len() - occupied_cells,
                singleton_cells,
                dense_cells,
                maximum_points_per_cell: self.xy_counts.iter().copied().max().unwrap_or(0),
                layered_cells: spans
                    .iter()
                    .filter(|&&span| span >= LAYERED_CELL_MINIMUM_Z_SPAN)
                    .count(),
                maximum_cell_z_span: spans.into_iter().fold(0.0_f64, f64::max),
                occupied_depth_bins: self.depth_counts.iter().filter(|&&count| count > 0).count(),
                intensity_minimum: self.intensity_minimum,
                intensity_maximum: self.intensity_maximum,
                rgb_minimum: self.rgb_minimum,
                rgb_maximum: self.rgb_maximum,
                classifications: self.classification_facts(),
                maximum_absolute_world_origin: origin
                    .into_iter()
                    .map(f64::abs)
                    .fold(0.0_f64, f64::max),
            })
        }

        fn observe(&mut self, record: &VisualRecord) {
            let minimum = self.relative_bounds.0;
            let maximum = self.relative_bounds.1;
            let x = condition_bin(record.relative_position[0], minimum[0], maximum[0]);
            let y = condition_bin(record.relative_position[1], minimum[1], maximum[1]);
            let cell = y * CONDITION_GRID_BINS + x;
            let z = record.relative_position[2];
            self.xy_counts[cell] += 1;
            self.xy_minimum_z[cell] = self.xy_minimum_z[cell].min(z);
            self.xy_maximum_z[cell] = self.xy_maximum_z[cell].max(z);
            self.depth_counts[condition_bin(z, minimum[2], maximum[2])] += 1;
            self.intensity_minimum = self.intensity_minimum.min(record.intensity);
            self.intensity_maximum = self.intensity_maximum.max(record.intensity);
            for channel in record.rgb {
                self.rgb_minimum = self.rgb_minimum.min(channel);
                self.rgb_maximum = self.rgb_maximum.max(channel);
            }
            self.classification_counts[usize::from(record.classification)] += 1;
        }

        fn layered_spans(&self) -> Vec<f64> {
            self.xy_counts
                .iter()
                .enumerate()
                .filter(|&(_, &count)| count > 1)
                .map(|(index, _)| self.xy_maximum_z[index] - self.xy_minimum_z[index])
                .collect()
        }

        fn classification_facts(&self) -> Vec<Value> {
            self.classification_counts
                .iter()
                .enumerate()
                .filter(|&(_, &count)| count > 0)
                .map(|(value, &count)| json!({ "value": value, "count": count }))
                .collect()
        }
    }

    fn derived_condition_names(summary: &ConditionSummary) -> Vec<&'static str> {
        let mut conditions = Vec::new();
        if summary.singleton_cells > 0 {
            conditions.push("sparse");
        }
        if summary.dense_cells > 0 {
            conditions.push("dense");
        }
        if summary.layered_cells > 0 && summary.occupied_depth_bins > 1 {
            conditions.push("layered");
        }
        if u64::from(summary.intensity_maximum - summary.intensity_minimum)
            >= HIGH_DYNAMIC_RANGE_MINIMUM_SPAN
            && u64::from(summary.rgb_maximum - summary.rgb_minimum)
                >= HIGH_DYNAMIC_RANGE_MINIMUM_SPAN
        {
            conditions.push("high_dynamic_range");
        }
        if summary.classifications.len() > 1 {
            conditions.push("classification");
        }
        if summary.maximum_absolute_world_origin >= LARGE_WORLD_MINIMUM_ABSOLUTE_ORIGIN
            && summary.minimum_positive_axis_spacing < 1.0
        {
            conditions.push("large_world");
        }
        conditions
    }

