//! Maintainer-only generator and verifier for the v0.16 browser fixture.

#[cfg(not(target_arch = "wasm32"))]
mod native {
    use std::error::Error;
    use std::fs;
    use std::path::{Path, PathBuf};
    use std::time::{SystemTime, UNIX_EPOCH};

    use las::point::{Classification, Format};
    use las::{Builder, Color, Point, Transform, Vector, Writer};
    use point_contracts::AttributeId;
    use point_index::{
        IndexRecipe, InspectionAttributeIds, PrepareLimits, prepare_fresh_with_recipe,
    };
    use serde_json::{Value, json};
    use sha2::{Digest, Sha256};
    use source_las::open;

    const POINT_COUNT: u64 = 70_000;
    const GRID_WIDTH: u64 = 350;
    const SOURCE_NAME: &str = "representative.las";
    const INDEX_NAME: &str = "representative.pidx";
    const RECORD_NAME: &str = "source-record.json";
    const MANIFEST_NAME: &str = "deployment.json";
    const INDEX_HEADER_BYTES: usize = 240;
    const NODE_RECORD_BYTES: usize = 168;
    const HEADER_AND_ROOT_BYTES: usize = INDEX_HEADER_BYTES + NODE_RECORD_BYTES;
    const SAMPLE_RECORD_BYTES: u64 = 42;
    const SOURCE_PROBE_BYTES: usize = 256;
    const WORLD_ORIGIN: [f64; 3] = [500_000.0, 4_600_000.0, 100.0];

    pub(super) fn run() -> Result<(), Box<dyn Error>> {
        let generated = TemporaryDirectory::create()?;
        generate(generated.path())?;
        let committed = Path::new(env!("CARGO_MANIFEST_DIR")).join("web/fixtures/v1");
        if std::env::args().nth(1).as_deref() == Some("--write") {
            publish(generated.path(), &committed)?;
            println!(
                "wrote deterministic v0.16 fixture to {}",
                committed.display()
            );
        } else {
            compare(generated.path(), &committed)?;
            println!("v0.16 browser streaming fixture matches regenerated bytes");
        }
        Ok(())
    }

    fn generate(directory: &Path) -> Result<(), Box<dyn Error>> {
        let source_path = directory.join(SOURCE_NAME);
        let index_path = directory.join(INDEX_NAME);
        write_source(&source_path)?;
        let source = open(&source_path).blocking_wait()?;
        let recipe = inspection_recipe()?;
        let index = prepare_fresh_with_recipe(
            source.clone(),
            &index_path,
            recipe,
            PrepareLimits::default(),
        )
        .blocking_wait()?;
        let source_record = newline_json(&serde_json::to_value(source.record())?)?;
        fs::write(directory.join(RECORD_NAME), &source_record)?;
        let manifest = build_manifest(&source_path, &index_path, &index)?;
        fs::write(directory.join(MANIFEST_NAME), newline_json(&manifest)?)?;
        Ok(())
    }

    fn inspection_recipe() -> Result<IndexRecipe, Box<dyn Error>> {
        let ids = InspectionAttributeIds::new(
            AttributeId::new(1)?,
            AttributeId::new(6)?,
            [
                AttributeId::new(16)?,
                AttributeId::new(17)?,
                AttributeId::new(18)?,
            ],
        )?;
        Ok(IndexRecipe::InspectionV1(ids))
    }

    fn build_manifest(
        source_path: &Path,
        index_path: &Path,
        index: &point_index::PreparedIndex,
    ) -> Result<Value, Box<dyn Error>> {
        let source_bytes = fs::read(source_path)?;
        let index_bytes = fs::read(index_path)?;
        let layout = read_root_layout(&index_bytes)?;
        let descriptor = index.descriptor();
        let root = index
            .hierarchy()
            .root()
            .ok_or("fixture index must have a root")?;
        if root.coverage_complete() || root.display_point_count() != layout.count {
            return Err("fixture root must have sampled disk-v2 coverage".into());
        }
        let source_sha256 = sha256_hex(&source_bytes);
        let index_sha256 = sha256_hex(&index_bytes);
        Ok(json!({
            "schema": "punctra-browser-stream-v1",
            "deployment_id": "repository-las-v1",
            "display_mapping": "rgb16_high_byte_rgba8_v1",
            "source": {
                "url": format!("./{SOURCE_NAME}"),
                "media_type": "application/vnd.las",
                "byte_length": source_bytes.len(),
                "strong_etag": format!("\"sha256-{source_sha256}\""),
                "sha256": source_sha256,
                "source_identity": descriptor.source().to_string(),
                "point_count": descriptor.source_point_count(),
                "probe": {
                    "offset": 0,
                    "length": SOURCE_PROBE_BYTES,
                    "sha256": sha256_hex(&source_bytes[..SOURCE_PROBE_BYTES]),
                }
            },
            "index": {
                "url": format!("./{INDEX_NAME}"),
                "byte_length": index_bytes.len(),
                "strong_etag": format!("\"sha256-{index_sha256}\""),
                "sha256": index_sha256,
                "disk_version": descriptor.disk_version(),
                "recipe_version": descriptor.recipe_version(),
                "display_sample_schema": 1,
                "source_identity": descriptor.source().to_string(),
                "source_point_count": descriptor.source_point_count(),
                "position_transform": {
                    "offset": descriptor.position_transform().offset(),
                    "scale": descriptor.position_transform().scale(),
                },
                "header_and_root": {
                    "offset": 0,
                    "length": HEADER_AND_ROOT_BYTES,
                    "sha256": sha256_hex(&index_bytes[..HEADER_AND_ROOT_BYTES]),
                },
                "root": {
                    "node_id": root.id().get(),
                    "coverage": "sampled",
                    "covered_point_count": root.covered_point_count(),
                    "display_point_count": root.display_point_count(),
                    "bounds": { "min": root.bounds().min(), "max": root.bounds().max() },
                    "world_origin": WORLD_ORIGIN,
                    "sample_range": {
                        "offset": layout.offset,
                        "length": layout.length,
                        "record_bytes": SAMPLE_RECORD_BYTES,
                        "count": layout.count,
                        "disk_checksum_blake3": encode_hex(&layout.disk_checksum),
                        "sha256": sha256_hex(layout.sample_bytes(&index_bytes)?),
                    }
                }
            }
        }))
    }

    fn write_source(path: &Path) -> Result<(), Box<dyn Error>> {
        let mut builder = Builder::from((1, 2));
        builder.file_source_id = 16;
        builder.point_format = Format::new(3)?;
        builder.transforms = Vector {
            x: Transform {
                scale: 0.01,
                offset: WORLD_ORIGIN[0],
            },
            y: Transform {
                scale: 0.01,
                offset: WORLD_ORIGIN[1],
            },
            z: Transform {
                scale: 0.01,
                offset: WORLD_ORIGIN[2],
            },
        };
        "Punctra v0.16 fixture".clone_into(&mut builder.generating_software);
        "Punctra browser acceptance".clone_into(&mut builder.system_identifier);
        let mut writer = Writer::from_path(path, builder.into_header()?)?;
        for ordinal in 0..POINT_COUNT {
            writer.write_point(fixture_point(ordinal))?;
        }
        writer.close()?;
        Ok(())
    }

    #[allow(clippy::cast_precision_loss)]
    fn fixture_point(ordinal: u64) -> Point {
        let column = ordinal % GRID_WIDTH;
        let row = ordinal / GRID_WIDTH;
        let x_ticks = i64::try_from(column).unwrap_or(0) * 25 - 4_350;
        let y_ticks = i64::try_from(row).unwrap_or(0) * 25 - 2_500;
        let z_ticks = (x_ticks * x_ticks - y_ticks * y_ticks) / 80_000;
        let red = u16::try_from((column * 173) % 65_536).unwrap_or(0);
        let green = u16::try_from((row * 311) % 65_536).unwrap_or(0);
        let blue = u16::try_from((ordinal * 29) % 65_536).unwrap_or(0);
        Point {
            x: WORLD_ORIGIN[0] + x_ticks as f64 * 0.01,
            y: WORLD_ORIGIN[1] + y_ticks as f64 * 0.01,
            z: WORLD_ORIGIN[2] + z_ticks as f64 * 0.01,
            intensity: u16::try_from(ordinal % 65_536).unwrap_or(0),
            return_number: 1,
            number_of_returns: 1,
            classification: Classification::Ground,
            gps_time: Some(1_600_000.0 + ordinal as f64 * 0.000_001),
            color: Some(Color::new(red, green, blue)),
            ..Point::default()
        }
    }

    fn read_root_layout(index: &[u8]) -> Result<RootLayout, Box<dyn Error>> {
        if index.len() < HEADER_AND_ROOT_BYTES || &index[..8] != b"PNIDX004" {
            return Err("generated index header is incomplete".into());
        }
        if read_u32(index, 8)? != 2 || read_u32(index, 12)? != 2 {
            return Err("generated index is not disk-v2 inspection recipe v2".into());
        }
        let root = INDEX_HEADER_BYTES;
        if read_u64(index, root)? != 1 || index[root + 128] != 0 {
            return Err("generated index root is not stable sampled node 1".into());
        }
        let count = read_u64(index, root + 88)?;
        let offset = read_u64(index, root + 112)?;
        let disk_checksum = index
            .get(root + 136..root + 168)
            .ok_or("generated root checksum is incomplete")?
            .try_into()?;
        let length = count
            .checked_mul(SAMPLE_RECORD_BYTES)
            .ok_or("root sample length overflowed")?;
        Ok(RootLayout {
            offset,
            length,
            count,
            disk_checksum,
        })
    }

    fn read_u32(bytes: &[u8], offset: usize) -> Result<u32, Box<dyn Error>> {
        Ok(u32::from_le_bytes(
            bytes
                .get(offset..offset + 4)
                .ok_or("missing u32")?
                .try_into()?,
        ))
    }

    fn read_u64(bytes: &[u8], offset: usize) -> Result<u64, Box<dyn Error>> {
        Ok(u64::from_le_bytes(
            bytes
                .get(offset..offset + 8)
                .ok_or("missing u64")?
                .try_into()?,
        ))
    }

    struct RootLayout {
        offset: u64,
        length: u64,
        count: u64,
        disk_checksum: [u8; 32],
    }

    impl RootLayout {
        fn sample_bytes<'index>(
            &self,
            index: &'index [u8],
        ) -> Result<&'index [u8], Box<dyn Error>> {
            let start = usize::try_from(self.offset)?;
            let length = usize::try_from(self.length)?;
            Ok(index
                .get(start..start + length)
                .ok_or("missing root samples")?)
        }
    }

    fn sha256_hex(bytes: &[u8]) -> String {
        encode_hex(&Sha256::digest(bytes))
    }

    fn encode_hex(bytes: &[u8]) -> String {
        const DIGITS: &[u8; 16] = b"0123456789abcdef";
        let mut encoded = String::with_capacity(bytes.len() * 2);
        for &byte in bytes {
            encoded.push(char::from(DIGITS[usize::from(byte >> 4)]));
            encoded.push(char::from(DIGITS[usize::from(byte & 0x0f)]));
        }
        encoded
    }

    fn newline_json(value: &Value) -> Result<Vec<u8>, serde_json::Error> {
        let mut bytes = serde_json::to_vec_pretty(value)?;
        bytes.push(b'\n');
        Ok(bytes)
    }

    fn publish(generated: &Path, committed: &Path) -> Result<(), Box<dyn Error>> {
        fs::create_dir_all(committed)?;
        for name in fixture_names() {
            fs::copy(generated.join(name), committed.join(name))?;
        }
        Ok(())
    }

    fn compare(generated: &Path, committed: &Path) -> Result<(), Box<dyn Error>> {
        for name in fixture_names() {
            let actual = fs::read(generated.join(name))?;
            let expected = fs::read(committed.join(name))?;
            if actual != expected {
                return Err(
                    format!("committed fixture {name} differs; regenerate with --write").into(),
                );
            }
        }
        Ok(())
    }

    const fn fixture_names() -> [&'static str; 4] {
        [SOURCE_NAME, INDEX_NAME, RECORD_NAME, MANIFEST_NAME]
    }

    struct TemporaryDirectory {
        path: PathBuf,
    }

    impl TemporaryDirectory {
        fn create() -> Result<Self, Box<dyn Error>> {
            let timestamp = SystemTime::now().duration_since(UNIX_EPOCH)?.as_nanos();
            for attempt in 0..1_000_u16 {
                let path = std::env::temp_dir().join(format!(
                    "punctra-browser-stream-fixture-{}-{timestamp}-{attempt}",
                    std::process::id()
                ));
                match fs::create_dir(&path) {
                    Ok(()) => return Ok(Self { path }),
                    Err(error) if error.kind() == std::io::ErrorKind::AlreadyExists => {}
                    Err(error) => return Err(error.into()),
                }
            }
            Err("could not create isolated fixture directory".into())
        }

        fn path(&self) -> &Path {
            &self.path
        }
    }

    impl Drop for TemporaryDirectory {
        fn drop(&mut self) {
            if let Err(error) = fs::remove_dir_all(&self.path) {
                eprintln!("warning: could not remove {}: {error}", self.path.display());
            }
        }
    }
}

#[cfg(not(target_arch = "wasm32"))]
fn main() -> Result<(), Box<dyn std::error::Error>> {
    native::run()
}

#[cfg(target_arch = "wasm32")]
fn main() {}
